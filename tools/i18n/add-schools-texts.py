def js(v):
    if isinstance(v, dict):
        return '{ ' + ', '.join(f'{k}: {json.dumps(x, ensure_ascii=False)}' for k, x in v.items()) + ' }'
    return json.dumps(v, ensure_ascii=False)

for lang in ('en', 'fr', 'es'):
    p = L(lang); s = open(p, encoding='utf-8').read()
    if '\n  sch: {' in s:
        print(f'{lang}: already has sch — skipped'); continue
    # side.new right after side.soon (first "soon:" inside "side: {")
