assert L['en'].keys() == L['fr'].keys() == L['es'].keys(), 'key sets differ'
for lang, d in L.items():
    p = os.path.join(LOC, lang, 'ui.js')
    s = open(p, encoding='utf-8').read()
    if '\n  legal: {' in s:
        print(lang, 'already has legal texts — skipped'); continue
    i = s.rstrip().rfind('});')
    body = ''.join('    %s: %s,\n' % (k, json.dumps(v, ensure_ascii=False)) for k, v in d.items())
    block = '  // v20261111b: /privacy, /terms, /delete-my-data, site footer, Account › Download my data\n  legal: {\n' + body + '  },\n'
    head = s[:i].rstrip()
    if not head.endswith(','): head += ','
    open(p, 'w', encoding='utf-8').write(head + '\n' + block + '});\n')
    print(lang, 'ok —', len(d), 'keys added')
